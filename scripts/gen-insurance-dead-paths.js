#!/usr/bin/env node
/**
 * Generates lib/insurance-dead-paths.js: the /insurance/* paths that are not
 * served (410 or redirected in vercel.json) and the state hubs each insurer
 * route actually builds.
 *
 * Why: the insurance link modules are client components, so they cannot import
 * vercel.json (136 KB) to check whether a link target is live. They kept linking
 * to retired and never-built pages (~4,000 links to 410s, plus 404s for
 * insurer x state combos the routes do not generate). This compact module lets
 * lib/insurance-links.js drop or reroute those links.
 *
 * Runs in prebuild. The output is committed so `next dev` works without it.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'insurance-dead-paths.js');

// 1) Dead paths: insurance routes ahead of `handle: filesystem` that 410 or redirect.
const routes = JSON.parse(fs.readFileSync(path.join(ROOT, 'vercel.json'), 'utf8')).routes || [];
const dead = new Set();
for (const r of routes) {
  if (r.handle === 'filesystem') break;
  if (!r.src || r.continue || !r.src.startsWith('/insurance/')) continue;
  const status = Number(r.status || 0);
  if (!(status === 410 || (status >= 300 && status < 400))) continue;
  const literal = r.src.replace(/\/\?$/, '');
  if (/[()|[\]*+?^$\\]/.test(literal)) {
    console.error(`gen-insurance-dead-paths: non-literal insurance route "${r.src}"; extend this script.`);
    process.exit(1);
  }
  dead.add(literal);
}

// 2) Built state hubs: the STATE_SLUGS keys each [segment] route generates.
const builtStates = {};
for (const insurer of ['aetna', 'blue-cross-blue-shield', 'united-healthcare']) {
  const file = path.join(ROOT, 'app', 'insurance', insurer, '[segment]', 'page.js');
  const src = fs.readFileSync(file, 'utf8');
  const m = src.match(/const STATE_SLUGS\s*=\s*\{([\s\S]*?)\};/);
  if (!m) {
    console.error(`gen-insurance-dead-paths: STATE_SLUGS not found in ${path.relative(ROOT, file)}`);
    process.exit(1);
  }
  builtStates[insurer] = [...m[1].matchAll(/['"]?([a-z-]+)['"]?\s*:/g)].map((x) => x[1]).sort();
}

const body = `// GENERATED by scripts/gen-insurance-dead-paths.js (runs in prebuild). Do not edit.
// Sources: vercel.json (410 / redirect routes) and app/insurance/*/[segment]/page.js.

export const DEAD_INSURANCE_PATHS = new Set(${JSON.stringify([...dead].sort(), null, 2)});

export const BUILT_INSURER_STATES = ${JSON.stringify(builtStates, null, 2)};
`;

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (prev !== body) fs.writeFileSync(OUT, body);
console.log(`✓ Insurance dead paths: ${dead.size} retired/redirected, built state hubs for ${Object.keys(builtStates).length} insurers`);
